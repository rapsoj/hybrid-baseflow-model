        f"{q[0]}-{q[-1]} interval coverage, baseline skill and extreme-event scores, on validation and test; both variants on identical samples; with GeoSmart the model is run once per member and the member predictive distributions are pooled as an equal-weight mixture (`pipeline/ensemble.py`); "
        "compared with climatology (training-flow quantiles), seasonal climatology (training-flow quantiles within "
        f"+/-{d['seasonal_window_days']} days of the target day of year) and persistence (flow at the origin held constant) via "
