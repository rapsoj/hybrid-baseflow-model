        "",
        f"<!-- config-hash: {config_hash(cfg)} -->",
        "_Generated by `python -m pipeline.describe` from `config.yaml` and the data on disk; do not edit by hand. "
        "Regenerate after changing the configuration (a test fails when this file is out of date)._",
        "",
        "## Data sources",
        "",
